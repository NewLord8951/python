from tkinter import Button, Tk, ttk, messagebox

def init():
    root = Tk()
    root.geometry("360x220+100+100")
    root.minsize(width=360, height=220)
    root.maxsize(width=360, height=220)
    root.title("A")
    button0 = Button(root, text="a")
    button0.pack(side="left")
    button1 = Button(root, text="a")
    button1.pack(side="right")   
    panel = ttk.Frame(root, padding=12)
    panel.pack(fill="x")
    title0 = ttk.Label(panel, text="a")
    title0.pack(pady=6)
    title1 = ttk.Label(panel, text="a")
    title1.pack(anchor="w")
    form = ttk.Frame(root, padding=12)
    form.pack(fill="x")
    label = ttk.Label(form, text="a")
    label.grid(row=0, column=0, sticky="w")
    entry = ttk.Entry(form, width=24)
    entry.grid(row=0, column=0, sticky="ew")
    form.columnconfigure(1, weight=1)
    groups = ("a", "aa", "aaa")
    group = ttk.Combobox(root, values=groups, state="readonly")
    group.current(1)
    group.pack()
    but = ttk.Button(root, text="a", command=lambda: messagebox.showinfo(title="a", message="aaaa"))
    but.pack()

    root.mainloop()

init()
